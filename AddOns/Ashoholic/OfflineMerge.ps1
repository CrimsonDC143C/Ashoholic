param(
    [string]$GameRoot = (Join-Path $PSScriptRoot "..\..\..")
)

$ErrorActionPreference = "Stop"

# SavedVariables must not be read while WoW is changing them. Do not change
# the source files: back them up, read only the data-only export, and write an
# inbox that the addon imports through its normal Data layer at next login.
$running = Get-Process -Name "Wow", "Wow-64", "ebonhold" -ErrorAction SilentlyContinue
if ($running) {
    throw "Close all WoW and Ebonhold game processes before running offline sync."
}

$root = (Resolve-Path -LiteralPath $GameRoot).Path
$accountsPath = Join-Path $root "WTF\Account"
$addonPath = Join-Path $root "Interface\AddOns\Ashoholic"
$inboxPath = Join-Path $addonPath "Sync\OfflineInbox.lua"
if (-not (Test-Path -LiteralPath $accountsPath -PathType Container)) {
    throw "WoW account directory not found: $accountsPath"
}
if (-not (Test-Path -LiteralPath (Join-Path $addonPath "Ashoholic.toc") -PathType Leaf)) {
    throw "Ashoholic is not installed at: $addonPath"
}
if (-not (Test-Path -LiteralPath (Split-Path -Parent $inboxPath) -PathType Container)) {
    throw "Ashoholic sync directory is missing: $(Split-Path -Parent $inboxPath)"
}

$sources = @()
foreach ($directory in Get-ChildItem -LiteralPath $accountsPath -Directory) {
    $savedFile = Join-Path $directory.FullName "SavedVariables\Ashoholic.lua"
    if (Test-Path -LiteralPath $savedFile -PathType Leaf) {
        $sources += [pscustomobject]@{ Account = $directory.Name; Path = $savedFile }
    }
}
if ($sources.Count -eq 0) {
    throw "No Ashoholic SavedVariables found under $accountsPath."
}

$backupName = (Get-Date -Format "yyyyMMdd-HHmmss") + "-" + [guid]::NewGuid().ToString("N").Substring(0, 8)
$backupRoot = Join-Path $root "WTF\AshoholicBackups"
if (-not (Test-Path -LiteralPath $backupRoot -PathType Container)) {
    New-Item -ItemType Directory -Path $backupRoot | Out-Null
}
$backupPath = Join-Path $backupRoot $backupName
New-Item -ItemType Directory -Path $backupPath | Out-Null
$exports = @()
$pattern = '\["ashoholicOfflineExport"\]\s*=\s*"(?<data>[0-9a-fA-F]+)"'
foreach ($source in $sources) {
    $accountBackup = Join-Path $backupPath $source.Account
    New-Item -ItemType Directory -Path $accountBackup | Out-Null
    $backupFile = Join-Path $accountBackup "Ashoholic.lua"
    Copy-Item -LiteralPath $source.Path -Destination $backupFile
    $text = [System.IO.File]::ReadAllText($backupFile)
    $matches = [regex]::Matches($text, $pattern)
    if ($matches.Count -eq 0) {
        Write-Warning "No offline export for $($source.Account). Log into that account with this addon version, then log out."
        continue
    }
    if ($matches.Count -ne 1) {
        throw "More than one offline export was found for $($source.Account); its backup is at $backupFile."
    }
    $encoded = $matches[0].Groups["data"].Value
    if ($encoded.Length -gt 524288 -or $encoded.Length % 2 -ne 0 -or -not $encoded.StartsWith("41534831")) {
        throw "The offline export for $($source.Account) is invalid; its backup is at $backupFile."
    }
    $exports += $encoded
}
if ($exports.Count -eq 0) {
    throw "No usable offline exports were found. Backups are at $backupPath."
}

$running = Get-Process -Name "Wow", "Wow-64", "ebonhold" -ErrorAction SilentlyContinue
if ($running) {
    throw "A game or launcher process started during offline sync. No inbox was changed. Backups: $backupPath"
}

$lines = @(
    "-- Generated by OfflineMerge.ps1; contains data-only account exports.",
    "local addonName = ...",
    '_G[addonName].OfflineSyncInbox = {'
)
foreach ($encoded in $exports) {
    $lines += '    "' + $encoded + '",'
}
$lines += "}"
$temporary = Join-Path (Split-Path -Parent $inboxPath) (".OfflineInbox-" + [guid]::NewGuid().ToString("N") + ".tmp")
try {
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($temporary, (($lines -join "`r`n") + "`r`n"), $utf8)
    if (Test-Path -LiteralPath $inboxPath -PathType Leaf) {
        [System.IO.File]::Replace($temporary, $inboxPath, (Join-Path $backupPath "OfflineInbox.previous.lua"))
    } else {
        [System.IO.File]::Move($temporary, $inboxPath)
    }
} finally {
    if (Test-Path -LiteralPath $temporary -PathType Leaf) {
        Remove-Item -LiteralPath $temporary
    }
}

Write-Host "Prepared $($exports.Count) account export(s). Log in on each account to import them."
Write-Host "Original SavedVariables were not changed. Backups: $backupPath"
